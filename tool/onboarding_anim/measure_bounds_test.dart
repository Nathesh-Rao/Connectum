// One-off measuring tool (run it, it is not part of the normal test run):
//   flutter test tool/onboarding_anim/measure_bounds_test.dart
// Samples every animation across its whole timeline, unions the bounds of all
// drawn elements (stroke, blur, springs, particles, packets, ripples included),
// limited to the original viewBox (the HTML clips there), prints which element
// sets each edge, and writes lib/core/widgets/onboarding_art/generated/
// content_bounds_data.dart.
import 'dart:io';
import 'dart:ui';

import 'package:connectum/core/widgets/onboarding_art/onboarding_art.dart';
import 'package:connectum/core/widgets/onboarding_art/onboarding_art_palette.dart';
import 'package:connectum/core/widgets/onboarding_art/svg_scene.dart';
import 'package:flutter_test/flutter_test.dart';

/// Seconds to sample per animation: the intro plus several loops (the shield's
/// waves are not periodic in its cycle, so it gets a long run).
const _spans = {
  OnboardingArtKind.shield: 60.0,
  OnboardingArtKind.network: 34.0,
  OnboardingArtKind.buildings: 45.0,
};

void main() {
  test('measure content bounds', () {
    final buf = StringBuffer()
      ..writeln('// GENERATED by tool/onboarding_anim/measure_bounds_test.dart, do not edit.')
      ..writeln('// Union of every drawn element over the whole timeline, inside the viewBox.')
      ..writeln()
      ..writeln("import 'dart:ui';")
      ..writeln();
    for (final kind in OnboardingArtKind.values) {
      final scene = kind.build(OnboardingArtPalette.authored);
      final art = kind.bind(scene);
      final r = SvgRenderer(scene);
      final vb = scene.viewBox;
      double l = double.infinity, t = double.infinity;
      double rt = -double.infinity, b = -double.infinity;
      final who = <String, String>{};
      for (var time = 0.0; time <= _spans[kind]!; time += 1 / 60) {
        art.render(time);
        for (final d in r.drawnRects()) {
          if (!d.rect.overlaps(vb)) continue;
          final c = d.rect.intersect(vb);
          if (c.left < l) { l = c.left; who['left'] = '${d.label} (${d.node.tag}) t=${time.toStringAsFixed(2)}'; }
          if (c.top < t) { t = c.top; who['top'] = '${d.label} (${d.node.tag}) t=${time.toStringAsFixed(2)}'; }
          if (c.right > rt) { rt = c.right; who['right'] = '${d.label} (${d.node.tag}) t=${time.toStringAsFixed(2)}'; }
          if (c.bottom > b) { b = c.bottom; who['bottom'] = '${d.label} (${d.node.tag}) t=${time.toStringAsFixed(2)}'; }
        }
      }
      double down(double v) => (v * 10).floorToDouble() / 10;
      double up(double v) => (v * 10).ceilToDouble() / 10;
      final box = Rect.fromLTRB(down(l), down(t), up(rt), up(b));
      // ignore: avoid_print
      print('${kind.name}: viewBox $vb -> content $box '
          '(${(box.width / vb.width * 100).toStringAsFixed(1)}% x ${(box.height / vb.height * 100).toStringAsFixed(1)}%) '
          'size ${box.width.toStringAsFixed(1)}x${box.height.toStringAsFixed(1)} ratio ${(box.width / box.height).toStringAsFixed(3)}\n'
          '   edges set by: $who');
      buf.writeln(
        'const ${kind.name}ContentBounds = Rect.fromLTRB(${box.left}, ${box.top}, ${box.right}, ${box.bottom});',
      );
    }
    // the network's mirror-symmetric layout: the left half is built and drawn
    // twice, so the bounds are the union of the half and its mirror, centred
    // on the axis; vertically centred on the steady picture (all persons
    // shown, before the outro), grown to cover the transients
    {
      final scene = OnboardingArtKind.network.build(OnboardingArtPalette.authored);
      final art = OnboardingArtKind.network.bind(scene, symmetric: true);
      final r = SvgRenderer(scene);
      final vb = scene.viewBox;
      final a = art.mirrorAxis!;
      final steadyFrom = (art.info['introEnd']! as double) + 0.3;
      final steadyTo = (art.info['outroStart']! as double) - 0.5;
      final period = art.duration;
      double l = double.infinity, t = double.infinity;
      double rt = -double.infinity, b = -double.infinity;
      double st = double.infinity, sb = -double.infinity;
      final who = <String, String>{};
      for (var time = 0.0; time <= 34.0; time += 1 / 60) {
        art.render(time);
        final inLoop = time % period;
        final isSteady = inLoop >= steadyFrom && inLoop <= steadyTo;
        for (final d in r.drawnRects()) {
          if (!d.rect.overlaps(vb)) continue;
          final c = d.rect.intersect(vb);
          final m = Rect.fromLTRB(2 * a - c.right, c.top, 2 * a - c.left, c.bottom);
          for (final q in [c, m]) {
            if (q.left < l) { l = q.left; who['left'] = '${d.label} (${d.node.tag}) t=${time.toStringAsFixed(2)}'; }
            if (q.top < t) { t = q.top; who['top'] = '${d.label} (${d.node.tag}) t=${time.toStringAsFixed(2)}'; }
            if (q.right > rt) { rt = q.right; who['right'] = '${d.label} (${d.node.tag}) t=${time.toStringAsFixed(2)}'; }
            if (q.bottom > b) { b = q.bottom; who['bottom'] = '${d.label} (${d.node.tag}) t=${time.toStringAsFixed(2)}'; }
          }
          if (isSteady) {
            st = st < c.top ? st : c.top;
            sb = sb > c.bottom ? sb : c.bottom;
          }
        }
      }
      final cy = (st + sb) / 2;
      final halfW = (a - l) > (rt - a) ? (a - l) : (rt - a);
      final halfH = (cy - t) > (b - cy) ? (cy - t) : (b - cy);
      double down(double v) => (v * 10).floorToDouble() / 10;
      double up(double v) => (v * 10).ceilToDouble() / 10;
      final hw = up(halfW), hh = up(halfH);
      final box = Rect.fromLTRB(a - hw, down(cy - hh), a + hw, up(cy + hh));
      // ignore: avoid_print
      print('network (symmetric): axis $a, content union x ${l.toStringAsFixed(1)}..${rt.toStringAsFixed(1)} '
          'y ${t.toStringAsFixed(1)}..${b.toStringAsFixed(1)}, steady y ${st.toStringAsFixed(1)}..${sb.toStringAsFixed(1)} '
          '(centre ${cy.toStringAsFixed(1)}) -> bounds $box ratio ${(box.width / box.height).toStringAsFixed(3)}\n   edges set by: $who');
      buf.writeln(
        'const networkSymContentBounds = Rect.fromLTRB(${box.left}, ${box.top}, ${box.right}, ${box.bottom});',
      );
      buf.writeln(
        'const networkSymSteadyCentreY = $cy;',
      );
    }
    File('lib/core/widgets/onboarding_art/generated/content_bounds_data.dart')
        .writeAsStringSync(buf.toString());
  });
}
