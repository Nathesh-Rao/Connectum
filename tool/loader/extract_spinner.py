#!/usr/bin/env python3
"""Generates the pull-to-refresh spinner data from the source SVG.

Usage: python3 tool/loader/extract_spinner.py [--src SVG] [--out DART]
Defaults: assets/icons/loader/spinner-double.svg
          -> lib/core/widgets/app_spinner/generated/spinner_double_data.dart

Reads, per <path>: its `d`, and from its <animateTransform type="rotate"> the
pivot, the direction (sign of to - from) and the duration. Also the viewBox.
Standard library only; output is deterministic.
"""
import argparse
import re
import xml.etree.ElementTree as ET

NS = '{http://www.w3.org/2000/svg}'


def num(v):
    return repr(float(v))


def seconds(dur):
    m = re.fullmatch(r'\s*([0-9.]+)\s*(ms|s)?\s*', dur)
    if not m:
        raise SystemExit('unsupported dur: ' + dur)
    value = float(m.group(1))
    return value / 1000 if m.group(2) == 'ms' else value


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', default='assets/icons/loader/spinner-double.svg')
    ap.add_argument('--out', default='lib/core/widgets/app_spinner/generated/spinner_double_data.dart')
    args = ap.parse_args()

    with open(args.src, encoding='utf-8') as f:
        text = f.read()
    root = ET.fromstring(re.sub(r'^\s*<!--.*?-->', '', text, flags=re.S))
    vb = [float(x) for x in root.get('viewBox').replace(',', ' ').split()]
    if len(vb) != 4:
        raise SystemExit('bad viewBox')

    paths = []
    for p in root.iter(NS + 'path'):
        anim = p.find(NS + 'animateTransform')
        if anim is None or anim.get('type') != 'rotate':
            raise SystemExit('path without a rotate animateTransform')
        if anim.get('repeatCount') != 'indefinite':
            raise SystemExit('expected repeatCount=indefinite')
        a0 = [float(x) for x in anim.get('from').split()]
        a1 = [float(x) for x in anim.get('to').split()]
        if a0[1:] != a1[1:] or abs(a1[0] - a0[0]) != 360:
            raise SystemExit('expected one full turn around one pivot')
        paths.append({
            'd': ' '.join(p.get('d').split()),
            'px': a0[1],
            'py': a0[2],
            'dir': 1 if a1[0] > a0[0] else -1,
            'dur': seconds(anim.get('dur')),
        })
    if not paths:
        raise SystemExit('no paths')

    lines = [
        '// GENERATED by tool/loader/extract_spinner.py from assets/icons/loader/spinner-double.svg, do not edit.',
        '// ignore_for_file: lines_longer_than_80_chars',
        '',
        'import \'../spinner_path_data.dart\';',
        '',
        'const double spinnerDoubleViewBoxX = %s;' % num(vb[0]),
        'const double spinnerDoubleViewBoxY = %s;' % num(vb[1]),
        'const double spinnerDoubleViewBoxWidth = %s;' % num(vb[2]),
        'const double spinnerDoubleViewBoxHeight = %s;' % num(vb[3]),
        '',
        'const List<SpinnerPathData> spinnerDoublePaths = [',
    ]
    for p in paths:
        lines += [
            '  SpinnerPathData(',
            "    d: '%s'," % p['d'].replace("'", "\\'"),
            '    pivotX: %s,' % num(p['px']),
            '    pivotY: %s,' % num(p['py']),
            '    direction: %d,' % p['dir'],
            '    durationSeconds: %s,' % num(p['dur']),
            '  ),',
        ]
    lines += ['];', '']
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print('viewBox %s' % ' '.join(num(x) for x in vb))
    for i, p in enumerate(paths):
        print('path %d: %d chars, pivot %g,%g, %s, %gs per turn' % (
            i + 1, len(p['d']), p['px'], p['py'],
            'clockwise' if p['dir'] > 0 else 'counter-clockwise', p['dur']))
    print('wrote ' + args.out)


if __name__ == '__main__':
    main()
