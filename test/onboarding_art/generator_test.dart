import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

const _files = {
  'shield-security.html': 'shield_art_data.dart',
  'network-icons.html': 'network_art_data.dart',
  'buildings-switching.html': 'buildings_art_data.dart',
};

Set<String> _htmlIds(String html) {
  final svg = RegExp(r'<svg\b.*?</svg>', dotAll: true).firstMatch(html)!.group(0)!;
  return RegExp(r'\sid="([^"]+)"').allMatches(svg).map((m) => m[1]!).toSet();
}

Set<String> _dartIds(String dart) =>
    RegExp(r"'id': '([^']+)'").allMatches(dart).map((m) => m[1]!).toSet();

void main() {
  const src = 'incoming/onboarding-animations';
  final hasSources = Directory(src).existsSync();

  Future<void> run(String out) async {
    final r = await Process.run('python3', [
      'tool/onboarding_anim/extract_art.py',
      '--src',
      src,
      '--out',
      out,
    ]);
    expect(r.exitCode, 0, reason: '${r.stderr}');
  }

  test(
    'running the tool twice gives identical output, equal to the committed files',
    () async {
      final a = Directory.systemTemp.createTempSync('art_a');
      final b = Directory.systemTemp.createTempSync('art_b');
      addTearDown(() {
        a.deleteSync(recursive: true);
        b.deleteSync(recursive: true);
      });
      await run(a.path);
      await run(b.path);
      for (final f in _files.values) {
        final one = File('${a.path}/$f').readAsStringSync();
        expect(File('${b.path}/$f').readAsStringSync(), one);
        expect(
          File('lib/core/widgets/onboarding_art/generated/$f').readAsStringSync(),
          one,
          reason: 'generated file is stale, re-run the tool',
        );
        expect(one.split('\n').first, startsWith('// GENERATED by tool/onboarding_anim/extract_art.py from'));
        expect(one.split('\n').first, endsWith('do not edit.'));
      }
    },
    skip: hasSources ? false : 'incoming/onboarding-animations is not present',
  );

  test(
    'each animation id list matches the HTML; the shield has its 46 path ids',
    () {
      for (final e in _files.entries) {
        final html = File('$src/${e.key}').readAsStringSync();
        final dart = File(
          'lib/core/widgets/onboarding_art/generated/${e.value}',
        ).readAsStringSync();
        expect(_dartIds(dart), _htmlIds(html), reason: e.key);
      }
      final shield = File(
        'lib/core/widgets/onboarding_art/generated/shield_art_data.dart',
      ).readAsStringSync();
      final pIds = _dartIds(shield).where((i) => RegExp(r'^p\d+$').hasMatch(i));
      // the file's comment says 64 original paths; 46 carry an id, the rest were merged
      expect(pIds.length, 46);
    },
    skip: hasSources ? false : 'incoming/onboarding-animations is not present',
  );
}
