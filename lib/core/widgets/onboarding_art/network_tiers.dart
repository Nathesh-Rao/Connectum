// Which persons the network animation shows. Edit the lists to change what
// is on screen; everything that belongs to a hidden person (its icon, ring,
// link, mask cut-out, comet, glow, flow dots, electrons) is left out with it,
// so nothing dangles. This is a design decision, not a bug.
//
// Ids: `c` (centre), `top`, `tr`, `br`, `bl`, `l` are the six hub avatars of
// the HTML. The small people of the HTML's tree are `<parent>-<n>`: the two
// people one hop out from `top` are `top-0` and `top-1`, from `tr` `tr-0` and
// `tr-1`, and so on; people one hop further are `top-0-0`, `top-0-1`, ...
// A person only shows when its parent shows (a hidden hub hides its people).
// `background` adds the whole tree of the HTML.
//
// Positions (scene units, viewBox -430 -290 2400x1600) and the HTML's own
// reveal times of the tier-2 people:
//   top-0 487,84 at 4.54 s    top-1 907,84 at 4.54 s
//   tr-0 1468,524 at 4.10 s   tr-1 1317,221 at 4.21 s
//   br-0 1321,1167 at 4.32 s  br-1 1452,855 at 4.43 s
//   bl-0 117,1168 at 4.32 s   bl-1 -14,856 at 4.43 s
// (`l-0` and `l-1` hang off the hidden `l`, so they stay out.)

/// Tier 1: the five persons that appear first in the HTML timeline.
const kNetworkTier1Persons = ['c', 'top', 'tr', 'br', 'bl'];

/// Tier 2: the people one hop from tier 1, connected into its links.
const kNetworkTier2Persons = [
  'top-0',
  'top-1',
  'tr-0',
  'tr-1',
  'br-0',
  'br-1',
  'bl-0',
  'bl-1',
];

/// Everything that is shown.
const kNetworkVisiblePersons = [
  ...kNetworkTier1Persons,
  ...kNetworkTier2Persons,
];

/// Seconds of idle time cut from the loop between the last reveal (tier 2 is
/// done at about 5.8 s) and the first electron (7.45 s with tier 2). Events
/// from the first electron on move earlier by this much, so about 0.6 s
/// remain; the idle motions keep running on the real time, so nothing jumps.
const kNetworkIdleTrim = 1.0;

// ---------------------------------------------------------------------------
// Symmetric layout (default). The picture is mirror-symmetric about the
// vertical axis x = [kNetworkAxisX]: the hub `c` sits on it, you list ONLY the
// left half, and the right half is generated by mirroring (the painter draws
// the left half twice, the second time flipped, so the two halves are the same
// pixels flipped at every moment of the animation).
//
// Ids: `ul` upper-left, `ll` lower-left (tier 1, the mid persons); their two
// small people are `ul-0`, `ul-1`, `ll-0`, `ll-1` (tier 2). The mirrored ids
// are `ur`, `lr`, `ur-0`, ... (see [kNetworkMirrorPairs]).
//
// To change what is shown edit the LEFT lists only; to move things edit the
// positions below. Symmetry stays automatic.
// ---------------------------------------------------------------------------

/// The axis, in scene units (the hub's x).
const kNetworkAxisX = 770.0;

/// Left half, tier 1: the mid persons (the hub `c` is on the axis).
const kNetworkLeftTier1Persons = ['ul', 'll'];

/// Left half, tier 2: the small people, two per mid person.
const kNetworkLeftTier2Persons = ['ul-0', 'ul-1', 'll-0', 'll-1'];

/// The id of the mirrored partner: `ul` -> `ur`, `ll` -> `lr`, `ul-0` -> `ur-0`.
String networkMirrorId(String id) =>
    '${id[0]}${id[1] == 'l' ? 'r' : 'l'}${id.substring(2)}';

/// id -> mirrored id for every left person (generated from the left lists).
final Map<String, String> kNetworkMirrorPairs = {
  for (final id in [...kNetworkLeftTier1Persons, ...kNetworkLeftTier2Persons])
    id: networkMirrorId(id),
};

/// Tier 1 of the symmetric layout: the hub, the left mid persons, their mirrors.
final List<String> kNetworkSymTier1Persons = [
  'c',
  ...kNetworkLeftTier1Persons,
  for (final id in kNetworkLeftTier1Persons) kNetworkMirrorPairs[id]!,
];

/// Tier 2 of the symmetric layout (left, then mirrored).
final List<String> kNetworkSymTier2Persons = [
  ...kNetworkLeftTier2Persons,
  for (final id in kNetworkLeftTier2Persons) kNetworkMirrorPairs[id]!,
];

/// Everything that is shown in the symmetric layout.
final List<String> kNetworkSymVisiblePersons = [
  ...kNetworkSymTier1Persons,
  ...kNetworkSymTier2Persons,
];

/// Which row each mid person is in (a mirrored pair shares its row).
const kNetworkMidRow = {'ul': 'upper', 'll': 'lower'};

/// Distance of a mid person from the axis and its height, per row (scene
/// units). The average of the old left and right distances: upper 465 / 401,
/// lower 490 / 388; heights 478 / 483 and 916 / 915.
const kNetworkRowDx = {'upper': 433.0, 'lower': 439.0};
const kNetworkRowY = {'upper': 480.0, 'lower': 916.0};

/// The drawn person of a pair: `top` (deep blue), `tr` (violet), `br` (blue),
/// `bl` (violet), `l` (sky blue). Both persons of a pair share it.
const kNetworkPersonByPair = {'upper': 'tr', 'lower': 'br'};

/// The badge of a pair: `chat`, `layers`, `check` or `calendar`. Both persons
/// of a pair share it; swap them here. The badge sits on the outer side.
const kNetworkBadgeByPair = {'upper': 'chat', 'lower': 'check'};

/// Which artwork draws each badge (the id suffix of `ic_<x>` in the art data).
const kNetworkBadgeArt = {
  'chat': 'top',
  'layers': 'tr',
  'check': 'br',
  'calendar': 'bl',
};

/// The artwork of the two small people of each mid person's row (alternating
/// blue / violet; the same on both halves).
const kNetworkKidArtByPair = {
  'upper': ['l', 'tr'],
  'lower': ['br', 'bl'],
};

/// Where the small people sit from their mid person: this far (scene units)
/// along the hub -> mid direction, fanned out by this angle (radians).
const kNetworkKidLength = 300.0;
const kNetworkKidSpread = 0.6;

/// When each row's person appears (script seconds); mirrored partners share it.
const kNetworkRowStart = {'upper': 1.4, 'lower': 1.8};

/// Lab switch default: symmetric layout on.
const kNetworkSymmetricDefault = true;

/// true (default): the right half is the exact mirror of the left, badge glyphs
/// included (a tick or a chat tail points the other way on the right).
/// false: only the positions are mirrored, the glyphs keep reading the right
/// way round (the two halves then differ by those two small glyphs).
const kNetworkFlipBadgeGlyphs = true;
